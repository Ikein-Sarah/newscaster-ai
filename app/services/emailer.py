import html
import os
import smtplib
from datetime import datetime
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from pathlib import Path

from dotenv import load_dotenv

load_dotenv(Path(__file__).resolve().parents[2] / ".env")

EMAIL_ADDRESS = os.getenv("EMAIL_ADDRESS")
EMAIL_APP_PASSWORD = os.getenv("EMAIL_APP_PASSWORD")
EMAIL_TO = os.getenv("EMAIL_TO")

TYPE_ORDER = ["announcement", "technical", "explainer", "roundup", "opinion", "quote"]

TYPE_LABELS = {
    "announcement": "Releases",
    "technical": "Deep dives",
    "explainer": "Explainers",
    "roundup": "Roundups",
    "opinion": "Commentary",
    "quote": "Quick reads",
}

CSS = """
body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Arial, sans-serif;
       line-height: 1.6; color: #333; max-width: 600px; margin: 0 auto; padding: 20px; background: #fff; }
h1 { font-size: 20px; color: #1a1a1a; margin: 0 0 4px; }
.date { color: #888; font-size: 14px; margin-bottom: 24px; }
h2 { font-size: 13px; text-transform: uppercase; letter-spacing: 1px; color: #888;
     margin: 28px 0 12px; padding-bottom: 6px; border-bottom: 1px solid #e5e5e5; }
.item { margin-bottom: 20px; }
.item a { color: #1a1a1a; text-decoration: none; font-weight: 600; font-size: 16px; }
.item a:hover { text-decoration: underline; }
.source { color: #999; font-size: 13px; margin: 2px 0 6px; }
.summary { color: #4a4a4a; margin: 0 0 8px; }
.angle { background: #f6f8fa; border-left: 3px solid #0066cc; padding: 8px 12px;
         color: #333; font-size: 14px; margin: 0; }
.angle b { color: #0066cc; }
.footer { color: #aaa; font-size: 12px; margin-top: 32px; border-top: 1px solid #e5e5e5; padding-top: 12px; }
"""


def _check_config():
    missing = [
        name
        for name, value in [
            ("EMAIL_ADDRESS", EMAIL_ADDRESS),
            ("EMAIL_APP_PASSWORD", EMAIL_APP_PASSWORD),
            ("EMAIL_TO", EMAIL_TO),
        ]
        if not value
    ]
    if missing:
        raise ValueError(f"Missing in .env: {', '.join(missing)}")


def build_html(articles) -> str:
    groups = {}
    for a in articles:
        groups.setdefault(a.story_type or "other", []).append(a)

    body = [
        "<h1>Newscaster</h1>",
        f"<div class='date'>{datetime.now().strftime('%A, %d %B')} &middot; {len(articles)} articles</div>",
    ]

    for story_type in TYPE_ORDER + ["other"]:
        if story_type not in groups:
            continue

        body.append(f"<h2>{TYPE_LABELS.get(story_type, story_type)}</h2>")

        for a in groups[story_type]:
            body.append("<div class='item'>")
            body.append(f"<a href='{html.escape(a.url)}'>{html.escape(a.title)}</a>")
            body.append(f"<div class='source'>{html.escape(a.source)}</div>")
            body.append(f"<p class='summary'>{html.escape(a.summary)}</p>")

            if a.angle and a.angle.strip().lower() != "nothing here":
                body.append(f"<p class='angle'><b>Angle:</b> {html.escape(a.angle)}</p>")

            body.append("</div>")

    body.append("<div class='footer'>Generated by Newscaster</div>")

    return f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<style>{CSS}</style>
</head>
<body>
{"".join(body)}
</body>
</html>"""


def build_text(articles) -> str:
    lines = [f"NEWSCASTER — {datetime.now().strftime('%d %B')}", ""]
    for a in articles:
        lines.append(f"{a.title} ({a.source})")
        lines.append(a.url)
        lines.append(a.summary)
        if a.angle and a.angle.strip().lower() != "nothing here":
            lines.append(f"Angle: {a.angle}")
        lines.append("")
    return "\n".join(lines)


def send_email(articles):
    _check_config()

    msg = MIMEMultipart("alternative")
    msg["Subject"] = f"Newscaster — {datetime.now().strftime('%d %b')}"
    msg["From"] = EMAIL_ADDRESS
    msg["To"] = EMAIL_TO

    msg.attach(MIMEText(build_text(articles), "plain"))
    msg.attach(MIMEText(build_html(articles), "html"))

    with smtplib.SMTP_SSL("smtp.gmail.com", 465) as smtp:
        smtp.login(EMAIL_ADDRESS, EMAIL_APP_PASSWORD)
        smtp.send_message(msg)

